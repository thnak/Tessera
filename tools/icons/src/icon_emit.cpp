[[nodiscard]] std::string join(const std::vector<std::string>& values, std::string_view separator) {
    std::string out;
    for (std::size_t i = 0; i < values.size(); ++i) {
        if (i != 0) {
            out.append(separator);
        }
        out.append(values[i]);
    }
    return out;
}

