std::string build_icons_header(const ImportResult& result) {
    std::string header;
    header.append("// SPDX-License-Identifier: MIT\n");
    header.append("//\n");
    header.append("// Generated by `tessera icons add`; do not edit.\n");
    header.append("//\n");
    header.append(
        "// Icons imported from pinned Iconify sets (ADR-047 item 8). Each entry names the\n");
    header.append(
        "// embedded SVG asset that `load_svg()` decodes into vector paths and the paint\n");
    header.append("// pass tints, so a `currentColor` icon follows the text color token.\n\n");
    header.append("#pragma once\n\n");
    header.append("#include <cstdint>\n");
    header.append("#include <span>\n");
    header.append("#include <string_view>\n\n");
    header.append("namespace tessera::icons::gen {\n\n");
    header.append("struct IconRef {\n");
    header.append("    std::string_view name; // \"<set>:<name>\"\n");
    header.append("    std::string_view asset; // embedded asset name\n");
    header.append("    std::uint32_t width = 0;\n");
    header.append("    std::uint32_t height = 0;\n");
    header.append("    bool monochrome = false;\n");
    header.append("};\n\n");
    header.append("inline constexpr IconRef kIcons[] = {\n");
    for (const ImportedIcon& icon : result.icons) {
        header.append("    {\"");
        header.append(icon.prefix);
        header.push_back(':');
        header.append(icon.name);
        header.append("\", \"");
        header.append(icon.asset);
        header.append("\", ");
        header.append(std::to_string(icon.width));
        header.append(", ");
        header.append(std::to_string(icon.height));
        header.append(", ");
        header.append(icon.monochrome ? "true" : "false");
        header.append("},\n");
    }
    header.append("};\n\n");
    header.append("[[nodiscard]] constexpr std::span<const IconRef> icons() noexcept {\n");
    header.append("    return kIcons;\n");
    header.append("}\n\n");
    header.append("} // namespace tessera::icons::gen\n");
    return header;
}

std::string build_embed_manifest(const ImportResult& result) {
    std::string manifest;
    manifest.append("# SPDX-License-Identifier: MIT\n");
    manifest.append("#\n");
    manifest.append("# Generated by `tessera icons add`; do not edit.\n");
    manifest.append("#\n");
    manifest.append(
        "# Feed this file to tessera_embed_assets(<target> MANIFEST <this file> ...) so "
        "the\n");
    manifest.append("# imported icons become embedded vector assets.\n");
    for (const ImportedIcon& icon : result.icons) {
        manifest.append(icon.asset);
        manifest.append(" = ");
        manifest.append(icon.asset);
        manifest.push_back('\n');
    }
    return manifest;
}

std::string build_attribution(const std::vector<AttributionSet>& sets) {
    std::string text;
    text.append("Icon set attribution\n");
    text.append("====================\n\n");
    text.append("Generated by `tessera icons add`; do not edit.\n\n");
    text.append("Each set below is a pinned Iconify package imported at build time and embedded "
                "as\n");
    text.append(
        "vector assets (ADR-047 item 8). CC-BY sets are listed with the attribution their\n");
    text.append("license requires; every set is listed with its license and copyright holder.\n");
    for (const AttributionSet& set : sets) {
        text.push_back('\n');
        text.append(set.prefix);
        if (!set.display_name.empty()) {
            text.append(" (");
            text.append(set.display_name);
            text.push_back(')');
        }
        text.push_back('\n');
        text.append("  License: ");
        text.append(set.license.empty() ? "not recorded" : set.license);
        if (!set.license_url.empty()) {
            text.append(" (");
            text.append(set.license_url);
            text.push_back(')');
        }
        text.push_back('\n');
        text.append("  Copyright: ");
        text.append(set.author.empty() ? "not recorded" : set.author);
        if (!set.author_url.empty()) {
            text.append(" (");
            text.append(set.author_url);
            text.push_back(')');
        }
        text.push_back('\n');
        if (requires_attribution(set.license_class)) {
            text.append("  Attribution required: icons by ");
            text.append(set.author.empty() ? "the set author" : set.author);
            text.append(" under ");
            text.append(set.license);
            if (!set.license_url.empty()) {
                text.append(", ");
                text.append(set.license_url);
            }
            text.push_back('\n');
        }
        text.append("  Icons: ");
        text.append(join(set.icons, ", "));
        text.push_back('\n');
    }
    return text;
}

