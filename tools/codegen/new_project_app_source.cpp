// The developer class of ADR-040. A template with no `// Note: bind::` marker needs no member, so
// this is the whole file; adding one is exactly the `add component` step of
// docs/guides/developer-workflow.md section 3.
std::string app_header(const Options& options) {
    std::string text;
    text += "// SPDX-License-Identifier: MIT\n";
    text += "//\n";
    text += "// Developer-owned (ADR-040). The generated base App.g.hpp is rewritten by\n";
    text += "// `tessera_codegen`; this class never is. Add one member per `// Note: bind::<id>`\n";
    text += "// marker in ui/App.tsx.\n";
    text += "#pragma once\n";
    text += "\n";
    text += "#include \"App.g.hpp\"\n";
    text += "\n";
    text += "namespace " + options.ns + " {\n";
    text += "\n";
    text += "class App final : public gen::AppBase<App> {\n";
    text += "private:\n";
    text += "    friend struct gen::AppBase<App>;\n";
    text += "};\n";
    text += "\n";
    text += "} // namespace " + options.ns + "\n";
    return text;
}

std::string app_source() {
    // Nothing to define yet: the class is header-only until it declares a binding. The TU exists
    // so `add_executable` has a second real source and the file is there to grow into.
    return R"(// SPDX-License-Identifier: MIT
//
// Developer-owned (ADR-040). Define the members App.hpp declares here; the class has none yet.

#include "App.hpp"
)";
}

// The entry point: the app-window path of samples/click-demo, which is the shipped public API.
// The generated component is built into a scene root, the project's stylesheet is compiled, and the
// window host runs the frame loop.
std::string main_source(const Options& options) {
    std::string text;
    text += "// SPDX-License-Identifier: MIT\n";
    text += "//\n";
    text +=
        "// Entry point for " + options.app_name + " (generated by `tessera new`). It follows\n";
    text += "// samples/click-demo: build the generated component into a scene root, compile the\n";
    text += "// project stylesheet, then run the app-window loop.\n";
    text += "//\n";
    text += "// Modes:\n";
    text += "//   " + options.app_name +
            " --capture out.png   one windowless frame, any Vulkan device\n";
    text +=
        "//   " + options.app_name + " [--frames N]      the window; N > 0 stops after N frames\n";
    text += "\n";
    text += "#include \"App.hpp\"\n";
    text += "\n";
    text += "#include \"tessera/app/window.hpp\"\n";
    text += "#include \"tessera/ui/scene/node.hpp\"\n";
    text += "#include \"tessera/ui/scene/update_scheduler.hpp\"\n";
    text += "#include \"tessera/ui/style/compiled_stylesheet.hpp\"\n";
    text += "\n";
    text += "#include <cstdlib>\n";
    text += "#include <fstream>\n";
    text += "#include <iostream>\n";
    text += "#include <iterator>\n";
    text += "#include <string>\n";
    text += "#include <vector>\n";
    text += "\n";
    text += "namespace {\n";
    text += "\n";
    text +=
        "// The scene root is the window's content node. Its id is outside the generated range.\n";
    text += "constexpr tessera::ui::NodeId kRootId = 900;\n";
    text += "\n";
    text +=
        "// The font is an asset, not a framework default: WindowOptions::font_path is required.\n";
    text +=
        "// Copy any OFL font (Inter, Noto Sans) to the first of these, or pass --font. There is\n";
    text += "// deliberately no environment-variable lookup: a build's behaviour should not depend "
            "on\n";
    text += "// the shell it was launched from.\n";
    text += "constexpr const char* kFontCandidates[] = {\n";
    text += "    \"assets/fonts/Inter-Regular.ttf\",\n";
    text += "    \"assets/fonts/NotoSans-Regular.ttf\",\n";
    text += "};\n";
    text += "\n";
    text += "std::string read_text(const std::string& path) {\n";
    text += "    std::ifstream in(path, std::ios::binary);\n";
    text += "    if (!in) {\n";
    text += "        return {};\n";
    text += "    }\n";
    text += "    return std::string(std::istreambuf_iterator<char>(in),\n";
    text += "                       std::istreambuf_iterator<char>());\n";
    text += "}\n";
    text += "\n";
    text += "// The first candidate that reads, else the first candidate (the error message names "
            "it).\n";
    text += "std::string resolve_font() {\n";
    text += "    for (const char* candidate : kFontCandidates) {\n";
    text += "        if (!read_text(candidate).empty()) {\n";
    text += "            return candidate;\n";
    text += "        }\n";
    text += "    }\n";
    text += "    return kFontCandidates[0];\n";
    text += "}\n";
    text += "\n";
    text += "} // namespace\n";
    text += "\n";
    text += "int main(int argc, char** argv) {\n";
    text += "    std::string capture;\n";
    text += "    std::string font = resolve_font();\n";
    text += "    int frames = 0;\n";
    text += "    for (int index = 1; index < argc; ++index) {\n";
    text += "        const std::string arg(argv[index]);\n";
    text += "        if (arg == \"--capture\" && index + 1 < argc) {\n";
    text += "            capture = argv[++index];\n";
    text += "        } else if (arg == \"--frames\" && index + 1 < argc) {\n";
    text += "            frames = std::atoi(argv[++index]);\n";
    text += "        } else if (arg == \"--font\" && index + 1 < argc) {\n";
    text += "            font = argv[++index];\n";
    text += "        } else if (arg == \"--help\" || arg == \"-h\") {\n";
    text += "            std::cout << \"usage: " + options.app_name +
            " [--capture out.png] [--frames N] [--font path]\\n\";\n";
    text += "            return 0;\n";
    text += "        } else {\n";
    text += "            std::cerr << \"" + options.app_name +
            ": unknown argument \" << arg << "
            "\"\\n\";\n";
    text += "            return 2;\n";
    text += "        }\n";
    text += "    }\n";
    text += "    if (read_text(font).empty()) {\n";
    text += "        std::cerr << \"" + options.app_name +
            ": cannot read the font '\" << font << \"'; pass --font \"\n";
    text += "                     \"(any OFL font works, for example Inter or Noto Sans)\\n\";\n";
    text += "        return 1;\n";
    text += "    }\n";
    text += "    const std::string css = read_text(\"ui/app.css\");\n";
    text += "    if (css.empty()) {\n";
    text += "        std::cerr << \"" + options.app_name +
            ": cannot read ui/app.css; run from the project root\\n\";\n";
    text += "        return 1;\n";
    text += "    }\n";
    text += "\n";
    text += "    tessera::ui::Node root{kRootId};\n";
    text += "    tessera::ui::UpdateScheduler scheduler;\n";
    text += "    " + options.ns + "::App app;\n";
    text += "    app.build(root);\n";
    text += "    app.mount();\n";
    text += "    app.attach_scheduler(scheduler);\n";
    text += "\n";
    text += "    tessera::app::WindowOptions options;\n";
    text += "    options.title = \"" + options.title + "\";\n";
    text += "    options.width = 900;\n";
    text += "    options.height = 620;\n";
    text += "    options.font_path = font;\n";
    text += "\n";
    text += "    if (!capture.empty()) {\n";
    text += "        tessera::app::CaptureOptions shot;\n";
    text += "        shot.width = options.width;\n";
    text += "        shot.height = options.height;\n";
    text += "        shot.font_path = font;\n";
    text += "        shot.scheduler = &scheduler;\n";
    text += "        const auto frame = tessera::app::capture_frame(\n";
    text += "            root, tessera::ui::style::compile_stylesheet(css), shot);\n";
    text += "        if (!frame) {\n";
    text += "            std::cout << \"" + options.app_name +
            ": skipped (Vulkan device unavailable)\\n\";\n";
    text += "            return 0;\n";
    text += "        }\n";
    text += "        std::cout << \"" + options.app_name + ": captured \" << capture << \" (\"\n";
    text += "                  << frame->width << \"x\" << frame->height << \")\\n\";\n";
    text += "        return 0;\n";
    text += "    }\n";
    text += "\n";
    text +=
        "    tessera::app::WindowHost host(root, tessera::ui::style::compile_stylesheet(css),\n";
    text += "                                  options, &scheduler);\n";
    text += "    if (!host.available()) {\n";
    text += "        std::cout << \"" + options.app_name +
            ": skipped (no window backend or presentation surface)\\n\";\n";
    text += "        return 0;\n";
    text += "    }\n";
    text += "    const tessera::app::WindowFrameStats stats =\n";
    text += "        host.run(static_cast<std::uint32_t>(frames));\n";
    text += "    std::cout << \"" + options.app_name + ": frames=\" << stats.frames\n";
    text += "              << \" presented=\" << stats.presented << \"\\n\";\n";
    text += "    return 0;\n";
    text += "}\n";
    return text;
}
