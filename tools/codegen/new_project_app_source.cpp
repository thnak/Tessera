namespace {

// `blank`: the smallest correct project. One component, one `Text`, no state, no hooks.
std::string blank_tsx() {
    return R"TSX(// SPDX-License-Identifier: MIT
//
// The app UI. `tessera_codegen` turns this file into App.g.hpp (ADR-040); the developer half is
// src/App.hpp. Change the tree here, then rebuild.

export function App() {
  return (
    <View className="app">
      <Text className="app-title">Hello, Tessera</Text>
    </View>
  );
}
)TSX";
}

// `counter`: one component with `useState` and inline setters, so `--template` is a real choice.
std::string counter_tsx() {
    return R"TSX(// SPDX-License-Identifier: MIT
//
// The app UI: one component holding one `useState` cell. `tessera_codegen` turns this file into
// App.g.hpp (ADR-040); the developer half is src/App.hpp. The inline setters need no `bind::`
// marker, so the developer class stays empty until you add C++ behavior of your own.

export function App() {
  const [count, setCount] = useState<int>(0);

  return (
    <View className="app">
      <Text className="app-title">Count: {count}</Text>
      <View className="app-row">
        <Button onClick={() => setCount(count + 1)}>Add</Button>
        <Button onClick={() => setCount(0)}>Reset</Button>
      </View>
    </View>
  );
}
)TSX";
}

} // namespace

// Type selectors would need no metadata; these are class selectors, as samples/gallery uses, so the
// sheet is written the way a real app stylesheet is.
std::string app_css(std::string_view app_name) {
    std::string text;
    text += "/* SPDX-License-Identifier: MIT */\n";
    text += "\n";
    text += "/* " + std::string(app_name) + "'s stylesheet (ui.styles in tessera.json). */\n";
    text += "\n";
    text += ".app {\n";
    text += "  display: flex;\n";
    text += "  flex-direction: column;\n";
    text += "  padding: 24px;\n";
    text += "  background-color: #0b1220;\n";
    text += "  color: #e2e8f0;\n";
    text += "}\n";
    text += "\n";
    text += ".app-title {\n";
    text += "  font-size: 20px;\n";
    text += "  margin-bottom: 12px;\n";
    text += "}\n";
    text += "\n";
    text += ".app-row {\n";
    text += "  display: flex;\n";
    text += "  flex-direction: row;\n";
    text += "}\n";
    text += "\n";
    text += "Button {\n";
    text += "  width: 110px;\n";
    text += "  height: 34px;\n";
    text += "  margin-right: 10px;\n";
    text += "  border-radius: 8px;\n";
    text += "  background-color: #2563eb;\n";
    text += "}\n";
    text += "\n";
    text += "Button:hover {\n";
    text += "  background-color: #1d4ed8;\n";
    text += "}\n";
    return text;
}

std::string app_tsx(std::string_view template_name) {
    return template_name == "counter" ? counter_tsx() : blank_tsx();
}

