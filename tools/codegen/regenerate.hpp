#pragma once

#include "diagnostics_json.hpp"

#include <string>
#include <vector>

// The codegen CLI driver, shared by tools/codegen/main.cpp and the CLI tests. Kept separate from
// the tessera_codegen library so the library keeps its IR-only dependency (AGENTS.md non-negotiable
// 4); the driver is the one place that may read JSX and call the front end.
namespace tessera::compiler::codegen::cli {

struct Options {
    std::vector<std::string> inputs; // .tsx files, as given on the command line
    std::string output_dir;
    std::string module_name; // --namespace; empty derives it from the first input
    bool check_only = false; // --check (mutually exclusive with the default --write)
    bool verbose = false;
    // --salt: overrides the id salt. By default the salt is `app.namespace` of the tessera.json at
    // --root or found above the first input (docs/specs/project-config-v1.md); with neither, the
    // identity stays unassigned. With a salt every component and node gets its numeric identity
    // (docs/specs/automation-ids-v1.md section 2) and the IR must validate completely.
    std::string salt;
    // --root: the project root that source paths in the ids are relative to (default: the
    // directory of the tessera.json that was found, else of the first input), so ids do not depend
    // on where the project is checked out.
    std::string root;
    // --emit-ir FILE: write the canonical IR JSON of the lowered module and generate no C++
    // (docs/specs/ir-v1.md). --out is not required.
    std::string emit_ir_path;
    // --emit-library-cpp FILE: write a C++ translation unit that rebuilds the lowered components as
    // IR data. This is the build-time path for packages/tessera-ui/*.tsx (issue #70); --out is not
    // required. The TSX sources are the source of truth, so an unlowerable source fails the run.
    std::string emit_library_cpp_path;
    // --diagnostics-json FILE: write the machine-readable diagnostics document
    // (docs/specs/compiler-diagnostics-v1.md) and generate nothing. The preview page calls the same
    // serializer through the Wasm entry point, which is what makes native and browser diagnostics
    // comparable (issue #165, docs/design/compiler-wasm.md section 6).
    std::string diagnostics_json_path;
    // --line-directives: emit `#line <tsx-line> "<tsx-file>"` into the generated base so a C++
    // compiler error or a debugger frame points at the TSX statement the code came from, not at a
    // line of the generated header (issue #78). Off by default: the directives change every
    // generated byte, and they are for the build whose diagnostics a developer reads, not for a
    // release build or a golden comparison.
    bool line_directives = false;
    // `base_dir`: the directory `inputs` are relative to when it is not empty. The inputs then stay
    // the project-relative names the diagnostics print (`ui/App.tsx`), and no process-wide current
    // directory is involved. The `tessera-mcp` server uses it to compile a folder that is not the
    // working directory; the CLI leaves it empty and keeps its working-directory behaviour.
    std::string base_dir;
    // `query`: the in-memory twin of `--diagnostics-json`: run the same stages, generate nothing,
    // write no file. The caller builds the document from `Outcome` with `diagnostics_document`.
    bool query = false;
    // `capture_ir` (with `query`): on a clean run keep the canonical IR JSON of the lowered module
    // in `Outcome::ir_json`, as `--emit-ir` would write it.
    bool capture_ir = false;
};

// One reported message. `text` is the human form the CLI prints (unchanged); `record` is the same
// diagnostic with its span intact, filled at the points that already hold a `jsx::Diagnostic` or an
// `ir::IrDiagnostic`. A message with no source location leaves the record's span empty rather than
// inventing a position (docs/specs/compiler-diagnostics-v1.md section 2).
struct Message {
    bool is_error = false;
    std::string text;
    DiagnosticRecord record;
};

struct Outcome {
    // 0: ok; 1: diagnostics or drift; 2: usage/setup.
    int exit_code = 0;
    std::vector<Message> messages;
    // Set only by `Options::capture_ir` on a run that reached the IR without a diagnostic.
    std::string ir_json;
};

// Regenerates the C++ of one project. Deterministic: first-error-only diagnostics, no partial
// output, and files are rewritten only when their merged content changed.
[[nodiscard]] Outcome run(const Options& options);

// The diagnostics records of a run, in report order: what `--diagnostics-json` writes and what the
// MCP `diagnostics` tool returns, built by this one function so the two cannot drift.
[[nodiscard]] std::vector<DiagnosticRecord> diagnostic_records(const Outcome& outcome);

// The whole document of a run: `primary_file` is the first input as the caller spelled it.
[[nodiscard]] std::string diagnostics_document(const Options& options, const Outcome& outcome);

} // namespace tessera::compiler::codegen::cli
