#pragma once

#include <iosfwd>
#include <span>
#include <string>
#include <string_view>
#include <vector>

// `tessera new <dir> [--template <name>]` (issue #77, docs/guides/project-generator.md).
//
// The scaffolder is a pure text generator plus one directory write: it renders a fixed set of files
// from a template and never reads the project back. Two consequences are load-bearing.
//
// 1. It downloads nothing. The "prebuilt toolchain" half of issue #77 is a release artifact and a
//    CI dependency, which is a separate decision; a scaffold that fetched one would turn the first
//    `tessera new` into a network call. The generated README and CMakeLists say what the project
//    needs and where to get it instead.
// 2. Its output is deterministic. The generated bytes are a function of (template, app name,
//    namespace) alone: no timestamp, no absolute path, no host-name, no random id, and POSIX
//    separators on every platform. Scaffolding the same inputs twice produces byte-identical trees,
//    which `tests/unit/harness/new_project_tests.cpp` asserts by comparison.
//
// The text lives in new_project_templates.cpp so this unit stays the CLI/IO half and the template
// bodies stay reviewable as the literal files they are.
namespace tessera::generator {

// One file of a scaffold. `path` is project-relative with POSIX separators, `text` is the exact
// bytes to write (UTF-8, LF line endings).
struct File {
    std::string path;
    std::string text;
};

// The substitutions a template may use. They are derived from the project directory name, so the
// same `tessera new hello` yields the same bytes on every machine. There is deliberately no field
// for the directory path itself: no generated file may contain one, so the generator never sees it.
struct Options {
    std::string app_name; // last path component, `^[a-z][a-z0-9-]*$` (project-config-v1 `app.name`)
    std::string ns;       // `app_name` with `-` -> `_`, `^[a-z][a-z0-9_]*$` (`app.namespace`)
    std::string title;    // `window.title`, defaulted from `app_name`
};

// The template names this build knows, sorted. `--template` accepts exactly these.
[[nodiscard]] std::vector<std::string> template_names();

// Renders a template. Empty when `template_name` is not in `template_names()`. Order is stable:
// manifest first, then the UI sources, the developer C++, the entry point, then the build files.
[[nodiscard]] std::vector<File> project_files(std::string_view template_name,
                                              const Options& options);

// `tessera new` with the arguments after the subcommand. Returns the documented CLI exit codes:
// 0 created, 1 a file could not be written, 2 usage or the target directory already holds files.
// Refuses to touch a non-empty directory before writing anything, so a failed run never leaves a
// half-scaffolded project and never overwrites a user's file.
[[nodiscard]] int run_new(std::span<const std::string_view> args, std::ostream& out,
                          std::ostream& err);

} // namespace tessera::generator
