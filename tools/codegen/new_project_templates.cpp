File file(std::string path, std::string text) {
    return File{std::move(path), std::move(text)};
}

// The project config. Fields and defaults are docs/specs/project-config-v1.md; `hooks.allowed` is
// the template's real hook set, so the compiler rejects a hook the template never opted into.
std::string tessera_json(const Options& options, std::vector<std::string> hooks) {
    std::string allowed;
    for (const std::string& hook : hooks) {
        allowed += allowed.empty() ? "" : ", ";
        allowed += "\"" + hook + "\"";
    }
    std::string text;
    text += "{\n";
    text += "  \"$schema\": \"https://tessera.dev/schema/project-v1.json\",\n";
    text += "  \"schemaVersion\": 1,\n";
    text += "  \"app\": {\n";
    text += "    \"name\": \"" + options.app_name + "\",\n";
    text += "    \"version\": \"0.1.0\",\n";
    text += "    \"entry\": \"ui/App.tsx\",\n";
    text += "    \"namespace\": \"" + options.ns + "\",\n";
    text += "    \"targets\": [\"windows\", \"linux\"],\n";
    text += "    \"renderer\": \"vulkan\"\n";
    text += "  },\n";
    text += "  \"window\": { \"title\": \"" + options.title +
            "\", \"width\": 900, \"height\": 620 },\n";
    text += "  \"ui\": {\n";
    text += "    \"sourceDirs\": [\"ui\"],\n";
    text += "    \"include\": [\"**/*.tsx\"],\n";
    text += "    \"hooks\": { \"allowed\": [" + allowed + "], \"strict\": true },\n";
    text += "    \"bindings\": { \"annotation\": \"// Note: bind::\", \"manifest\": "
            "\"generated/bindings.json\" }\n";
    text += "  },\n";
    text += "  \"codegen\": {\n";
    text += "    \"outDir\": \"generated\",\n";
    text += "    \"namespace\": \"" + options.ns + "::gen\",\n";
    text += "    \"deterministic\": true\n";
    text += "  },\n";
    text += "  \"build\": { \"preset\": \"dev\", \"staticRuntime\": true },\n";
    text += "  \"runtime\": { \"fixedTimestepHz\": 60, \"renderOnDemand\": true },\n";
    text += "  \"diagnostics\": { \"level\": \"info\", \"telemetry\": false }\n";
    text += "}\n";
    return text;
}

// Two routes to the framework, in the order a new user needs them. Nothing is fetched: route A is
// an installed SDK (issue #77 task 2, not shipped yet), route B is the checkout the user already
// has. A configure failure names both instead of dumping a find_package error.
std::string cmake_lists(const Options& options) {
    std::string text;
    text += "# SPDX-License-Identifier: MIT\n";
    text += "#\n";
    text += "# " + options.app_name + " -- generated by `tessera new` (issue #77).\n";
    text += "#\n";
    text += "# This project needs the Tessera framework. `tessera new` downloads nothing, so pick "
            "one of:\n";
    text += "#\n";
    text += "#   A. an installed Tessera SDK that provides TesseraConfig.cmake:\n";
    text += "#        cmake --preset dev -DCMAKE_PREFIX_PATH=<sdk>\n";
    text += "#   B. a Tessera checkout (builds the framework as part of this project):\n";
    text += "#        cmake --preset dev -DTESSERA_SOURCE_DIR=<checkout>\n";
    text += "#\n";
    text += "# Route B is the one that works today; a release archive for route A is tracked by "
            "issue\n";
    text += "# #77 and does not exist yet.\n";
    text += "\n";
    text += "cmake_minimum_required(VERSION 3.24)\n";
    text += "project(" + options.app_name + " LANGUAGES C CXX)\n";
    text += "\n";
    text += "set(CMAKE_CXX_STANDARD 23)\n";
    text += "set(CMAKE_CXX_STANDARD_REQUIRED ON)\n";
    text += "set(CMAKE_CXX_EXTENSIONS OFF)\n";
    text += "set(CMAKE_EXPORT_COMPILE_COMMANDS ON)\n";
    text += "\n";
    text += "# Static linking is a hard requirement (ADR-012; tessera.json build.staticRuntime "
            "must be\n";
    text +=
        "# true). The app and the framework must agree on the C/C++ runtime, and this setting is\n";
    text += "# inherited by add_subdirectory below, so set it before the framework is added.\n";
    text += "if (MSVC)\n";
    text += "    set(CMAKE_MSVC_RUNTIME_LIBRARY \"MultiThreaded$<$<CONFIG:Debug>:Debug>\")\n";
    text += "endif ()\n";
    text += "\n";
    text += "set(TESSERA_SOURCE_DIR \"\" CACHE PATH\n";
    text +=
        "    \"Tessera checkout to build this project against (route B). Empty: find_package\")\n";
    text += "\n";
    text += "if (TESSERA_SOURCE_DIR)\n";
    text += "    # A framework checkout brings its own tests and PoCs; a new app wants neither.\n";
    text += "    set(TESSERA_BUILD_TESTS OFF CACHE BOOL \"\" FORCE)\n";
    text += "    set(TESSERA_BUILD_POC OFF CACHE BOOL \"\" FORCE)\n";
    text += "    add_subdirectory(${TESSERA_SOURCE_DIR} ${CMAKE_BINARY_DIR}/tessera)\n";
    text += "else ()\n";
    text += "    find_package(Tessera CONFIG REQUIRED)\n";
    text += "endif ()\n";
    text += "\n";
    text += "# The generated base lives in the build output directory, never in the source tree\n";
    text +=
        "# (docs/guides/developer-workflow.md: generated code is build output, not committed).\n";
    text += "set(GENERATED_DIR ${CMAKE_CURRENT_BINARY_DIR}/generated)\n";
    text += "set(APP_TSX ${CMAKE_CURRENT_SOURCE_DIR}/ui/App.tsx)\n";
    text += "file(MAKE_DIRECTORY ${GENERATED_DIR})\n";
    text += "\n";
    text += "add_custom_command(\n";
    text += "    OUTPUT ${GENERATED_DIR}/App.g.hpp\n";
    text += "    COMMAND $<TARGET_FILE:tessera_codegen_cli> --write --out ${GENERATED_DIR}\n";
    text += "            --namespace " + options.ns +
            " --root ${CMAKE_CURRENT_SOURCE_DIR} ${APP_TSX}\n";
    text += "    DEPENDS tessera_codegen_cli ${APP_TSX}\n";
    text += "    COMMENT \"Generating App.g.hpp from ui/App.tsx\"\n";
    text += "    VERBATIM)\n";
    text += "\n";
    text += "add_executable(" + options.app_name + "\n";
    text += "    src/main.cpp\n";
    text += "    src/App.cpp\n";
    text += "    ${GENERATED_DIR}/App.g.hpp)\n";
    text += "\n";
    text +=
        "# src/ first: `#include \"App.hpp\"` must resolve to the developer class, never to the\n";
    text +=
        "# identical-name stub the generator scaffolds into GENERATED_DIR for a new component.\n";
    text += "target_include_directories(" + options.app_name + " PRIVATE\n";
    text += "    ${CMAKE_CURRENT_SOURCE_DIR}/src\n";
    text += "    ${GENERATED_DIR})\n";
    text += "target_compile_features(" + options.app_name + " PRIVATE cxx_std_23)\n";
    text += "\n";
    text += "if (TARGET tessera_app_window)\n";
    text += "    target_link_libraries(" + options.app_name + " PRIVATE tessera_app_window)\n";
    text += "else ()\n";
    text += "    target_link_libraries(" + options.app_name + " PRIVATE Tessera::app_window)\n";
    text += "endif ()\n";
    text += "\n";
    text += "if (MSVC)\n";
    text +=
        "    target_compile_options(" + options.app_name + " PRIVATE /W4 /permissive- /utf-8)\n";
    text += "else ()\n";
    text +=
        "    target_compile_options(" + options.app_name + " PRIVATE -Wall -Wextra -Wpedantic)\n";
    text += "endif ()\n";
    return text;
}

// The presets mirror CMakePresets.json's names so the commands in the README match the repo's.
std::string cmake_presets() {
    return R"PRESETS({
  "version": 5,
  "cmakeMinimumRequired": { "major": 3, "minor": 24, "patch": 0 },
  "configurePresets": [
    {
      "name": "dev",
      "displayName": "Ninja Debug",
      "generator": "Ninja",
      "binaryDir": "${sourceDir}/build/dev",
      "cacheVariables": { "CMAKE_BUILD_TYPE": "Debug" }
    },
    {
      "name": "release",
      "displayName": "Ninja Release",
      "generator": "Ninja",
      "binaryDir": "${sourceDir}/build/release",
      "cacheVariables": { "CMAKE_BUILD_TYPE": "Release" }
    }
  ],
  "buildPresets": [
    { "name": "dev", "configurePreset": "dev" },
    { "name": "release", "configurePreset": "release" }
  ]
}
)PRESETS";
}

// The repository's .clang-format (LLVM base, 4 spaces, 100 columns), so a generated project formats
// the same way the framework does. Kept in sync by hand; it is five lines of style, not a contract.
std::string clang_format() {
    return R"FORMAT(---
Language: Cpp
BasedOnStyle: LLVM
Standard: Latest
IndentWidth: 4
TabWidth: 4
UseTab: Never
ColumnLimit: 100
PointerAlignment: Left
ReferenceAlignment: Left
InsertBraces: true
FixNamespaceComments: true
MaxEmptyLinesToKeep: 1
)FORMAT";
}

// Generated output and build trees are never committed (docs/guides/developer-workflow.md).
std::string gitignore() {
    return R"GIT(build/
generated/
*.user
)GIT";
}

// `ui/elements.json`: the custom-element manifest of docs/specs/custom-elements-v1.md. An empty
// list is the documented "no custom elements" project, and it keeps the file valid rather than
// absent.
std::string elements_json() {
    return R"ELEMENTS({
  "elementsVersion": 1,
  "elements": []
}
)ELEMENTS";
}

// The README. It states the five-minute claim's real content: the files, what is proven, and the
// one manual prerequisite (a toolchain), rather than promising a wall-clock number.
std::string readme(const Options& options, std::string_view template_name) {
    std::string text;
    text += "# " + options.app_name + "\n";
    text += "\n";
    text += "Created by `tessera new --template " + std::string(template_name) + "` (issue #77).\n";
    text += "\n";
    text += "## What is here\n";
    text += "\n";
    text += "```text\n";
    text += options.app_name + "/\n";
    text += "|-- tessera.json        project configuration (docs/specs/project-config-v1.md)\n";
    text += "|-- CMakeLists.txt      builds the app against a Tessera checkout or SDK\n";
    text += "|-- CMakePresets.json   dev/release presets\n";
    text += "|-- .clang-format       the framework's formatting\n";
    text += "|-- README.md\n";
    text += "|-- src/\n";
    text += "|   |-- main.cpp        entry point (samples/click-demo shape)\n";
    text += "|   |-- App.hpp         developer class, derives from gen::AppBase<App> (ADR-040)\n";
    text += "|   `-- App.cpp\n";
    text += "`-- ui/\n";
    text += "    |-- App.tsx         the UI (JSX/TSX)\n";
    text += "    |-- app.css         the app stylesheet\n";
    text += "    `-- elements.json   custom-element manifest (empty)\n";
    text += "```\n";
    text += "\n";
    text += "`generated/` and `build/` are build output: `tessera_codegen` writes `App.g.hpp` "
            "there and\n";
    text += "they are gitignored. Never edit `App.g.hpp`; change `ui/App.tsx` and regenerate.\n";
    text += "\n";
    text += "## Build it\n";
    text += "\n";
    text += "`tessera new` downloaded nothing, so the framework has to be somewhere already.\n";
    text += "\n";
    text += "```bash\n";
    text += "# Route B (works today): build against a Tessera checkout.\n";
    text += "cmake --preset dev -DTESSERA_SOURCE_DIR=/path/to/Tessera\n";
    text += "cmake --build --preset dev\n";
    text += "./build/dev/" + options.app_name + " --frames 120\n";
    text += "\n";
    text +=
        "# Route A: an installed Tessera SDK providing TesseraConfig.cmake (issue #77 task 2,\n";
    text += "# not released yet).\n";
    text += "cmake --preset dev -DCMAKE_PREFIX_PATH=/path/to/tessera-sdk\n";
    text += "```\n";
    text += "\n";
    text += "Requirements are the framework's (docs/guides/getting-started.md): CMake >= 3.24, a "
            "C++23\n";
    text += "compiler, the Vulkan SDK with `VULKAN_SDK` set and `glslc` on `PATH`, and a font.\n";
    text += "\n";
    text += "## Regenerate\n";
    text += "\n";
    text += "```bash\n";
    text += "tessera_codegen --write --out generated --namespace " + options.ns +
            " --root . ui/App.tsx\n";
    text += "```\n";
    text += "\n";
    text += "CMake runs that for you. The developer class `src/App.hpp`/`App.cpp` is written once "
            "and is\n";
    text += "never rewritten by the generator (ADR-040).\n";
    text += "\n";
    text += "## Add a component\n";
    text += "\n";
    text += "1. Create `ui/Widget.tsx`.\n";
    text += "2. Put `// Note: bind::<id>` next to logic that needs developer C++.\n";
    text += "3. Regenerate; the generator scaffolds `Widget.hpp`/`.cpp` into `generated/` once.\n";
    text += "4. Move or copy that class next to `src/App.hpp` and fill in the members.\n";
    text += "\n";
    text += "Version control is yours to initialise: `tessera new` does not run `git init`.\n";
    return text;
}

