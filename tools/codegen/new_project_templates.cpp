// The project and build file bodies `tessera new` writes (issue #77,
// docs/guides/project-generator.md): tessera.json, CMakeLists.txt, CMakePresets.json,
// .clang-format, .gitignore, ui/elements.json and README.md. The app sources the user edits
// (ui/App.tsx, the developer class, src/main.cpp) are in new_project_app_source.cpp.
//
// Every byte here is a function of the template name and `Options` alone, so two runs with the same
// arguments produce identical trees. Nothing is read from the environment, the clock or the
// filesystem, no path is made absolute, and no separator is host-dependent: the templates are
// POSIX-style project-relative paths and LF text on every platform.
//
// The layout follows docs/guides/project-generator.md "Generated project layout" where that tree
// names a file. Where the doc's shape is aspirational it follows an existing sample instead; the
// reasoning is in new_project_app_source.cpp, which owns those files.
//
// No font and no theme asset is scaffolded. Both are licensed third-party assets; the README says
// where they go and `tessera new` never copies or downloads one.

