std::vector<std::string> template_names() {
    return {"blank", "counter"};
}

std::vector<File> project_files(std::string_view template_name, const Options& options) {
    if (std::find(template_names().begin(), template_names().end(), template_name) ==
        template_names().end()) {
        return {};
    }
    const bool counter = template_name == "counter";
    const std::vector<std::string> hooks =
        counter ? std::vector<std::string>{"useState"} : std::vector<std::string>{};
    std::vector<File> files;
    files.push_back(file("tessera.json", tessera_json(options, hooks)));
    files.push_back(file("CMakeLists.txt", cmake_lists(options)));
    files.push_back(file("CMakePresets.json", cmake_presets()));
    files.push_back(file(".clang-format", clang_format()));
    files.push_back(file(".gitignore", gitignore()));
    files.push_back(file("README.md", readme(options, template_name)));
    files.push_back(file("ui/App.tsx", app_tsx(template_name)));
    files.push_back(file("ui/app.css", app_css(options.app_name)));
    files.push_back(file("ui/elements.json", elements_json()));
    files.push_back(file("src/App.hpp", app_header(options)));
    files.push_back(file("src/App.cpp", app_source()));
    files.push_back(file("src/main.cpp", main_source(options)));
    return files;
}

