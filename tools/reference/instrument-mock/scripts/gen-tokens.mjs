// Writes src/generated/tokens.css from packages/tessera-ui/themes/instrument.theme.json: one rule per
// theme, selected by [data-theme="<id>"] on <html>; the theme named by "start" also owns :root so the
// page has tokens before any attribute is set. Token values are copied verbatim and in file order, so
// the output is a pure function of the JSON. `--check` compares instead of writing and exits 1 when the
// committed file is stale.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const appRoot = join(here, "..");
const repoRoot = join(appRoot, "..", "..", "..");
const themeFile = join(repoRoot, "packages", "tessera-ui", "themes", "instrument.theme.json");
const outFile = join(appRoot, "src", "generated", "tokens.css");

export function renderTokens(json) {
  const theme = JSON.parse(json);
  if (theme.schemaVersion !== 1) {
    throw new Error(`unsupported theme schemaVersion ${theme.schemaVersion}`);
  }
  const lines = [
    "/* GENERATED by scripts/gen-tokens.mjs from packages/tessera-ui/themes/instrument.theme.json.",
    "   Do not edit; run `npm run tokens`. */",
  ];
  for (const [id, tokens] of Object.entries(theme.themes)) {
    const version = theme.themeVersions?.[id] ?? "unversioned";
    lines.push("", `/* ${id} ${version}${id === theme.start ? " (start theme)" : ""} */`);
    lines.push(id === theme.start ? `:root,\n[data-theme="${id}"] {` : `[data-theme="${id}"] {`);
    for (const [name, value] of Object.entries(tokens)) {
      if (!name.startsWith("--")) throw new Error(`${id}: token ${name} is not a custom property`);
      lines.push(`  ${name}: ${value};`);
    }
    lines.push("}");
  }
  return lines.join("\n") + "\n";
}

const expected = renderTokens(readFileSync(themeFile, "utf8"));
const rel = relative(appRoot, outFile).replaceAll("\\", "/");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8").replace(/\r\n/g, "\n");
  } catch {
    current = "";
  }
  if (current !== expected) {
    console.error(`${rel} is stale; run \`npm run tokens\` and commit it.`);
    process.exit(1);
  }
  console.log(`tokens: ok (${rel} matches instrument.theme.json)`);
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, expected);
  console.log(`tokens: wrote ${rel}`);
}
