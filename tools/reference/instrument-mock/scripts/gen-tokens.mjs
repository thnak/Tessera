// Writes src/generated/tokens.css from two inputs:
//   - packages/tessera-ui/themes/instrument.theme.json (the versioned Instrument theme, never edited here)
//   - tokens/material.tokens.json (this mock's proposed material layer: gradients, raised/well/engraved
//     recipes, glow, extra radii), keyed by the same theme ids.
// One rule per theme, selected by [data-theme="<id>"] on <html>; the theme named by "start" also owns
// :root. Values are copied verbatim and in file order (theme tokens, then shared material tokens, then
// the theme's material tokens), so the output is a pure function of the two files. `--check` compares
// instead of writing and exits 1 when the committed file is stale.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const appRoot = join(here, "..");
const repoRoot = join(appRoot, "..", "..", "..");
const themeFile = join(repoRoot, "packages", "tessera-ui", "themes", "instrument.theme.json");
const materialFile = join(appRoot, "tokens", "material.tokens.json");
const outFile = join(appRoot, "src", "generated", "tokens.css");

function checkNames(where, tokens) {
  for (const name of Object.keys(tokens)) {
    if (!name.startsWith("--")) throw new Error(`${where}: token ${name} is not a custom property`);
  }
}

export function renderTokens(themeJson, materialJson) {
  const theme = JSON.parse(themeJson);
  const material = JSON.parse(materialJson);
  if (theme.schemaVersion !== 1) throw new Error(`unsupported theme schemaVersion ${theme.schemaVersion}`);
  if (material.schemaVersion !== 1) throw new Error(`unsupported material schemaVersion ${material.schemaVersion}`);

  const ids = Object.keys(theme.themes);
  const materialIds = Object.keys(material.themes);
  if (ids.join() !== materialIds.join()) {
    throw new Error(`material themes [${materialIds}] must match theme ids [${ids}] in order`);
  }
  const keySet = (id) => Object.keys(material.themes[id]).join();
  for (const id of ids) {
    if (keySet(id) !== keySet(ids[0])) throw new Error(`material theme ${id} has a different token set`);
  }
  checkNames("shared", material.shared);

  const lines = [
    "/* GENERATED by scripts/gen-tokens.mjs from packages/tessera-ui/themes/instrument.theme.json",
    "   and tokens/material.tokens.json. Do not edit; run `npm run tokens`. */",
  ];
  for (const id of ids) {
    const version = theme.themeVersions?.[id] ?? "unversioned";
    lines.push("", `/* ${id} ${version}${id === theme.start ? " (start theme)" : ""} + material layer */`);
    lines.push(id === theme.start ? `:root,\n[data-theme="${id}"] {` : `[data-theme="${id}"] {`);
    for (const [where, tokens] of [[id, theme.themes[id]], ["shared", material.shared], [`material ${id}`, material.themes[id]]]) {
      checkNames(where, tokens);
      for (const [name, value] of Object.entries(tokens)) lines.push(`  ${name}: ${value};`);
    }
    lines.push("}");
  }
  return lines.join("\n") + "\n";
}

const expected = renderTokens(readFileSync(themeFile, "utf8"), readFileSync(materialFile, "utf8"));
const rel = relative(appRoot, outFile).replaceAll("\\", "/");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8").replace(/\r\n/g, "\n");
  } catch {
    current = "";
  }
  if (current !== expected) {
    console.error(`${rel} is stale; run \`npm run tokens\` and commit it.`);
    process.exit(1);
  }
  console.log(`tokens: ok (${rel} matches instrument.theme.json + material.tokens.json)`);
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, expected);
  console.log(`tokens: wrote ${rel}`);
}
