// A manifest with no assets still generates a bundle that compiles, links and behaves: zero
// entries, zero payload bytes, and every lookup reports not_found (invalid names still report
// invalid_name).

#include "asset_zero_bundle_tests_assets.hpp"
#include "tessera/ui/assets/asset_bundle.hpp"

#include <iostream>

namespace {

namespace assets = tessera::ui::assets;

[[nodiscard]] bool expect(bool condition, const char* message) {
    if (!condition) {
        std::cerr << "asset_zero_bundle: " << message << "\n";
    }
    return condition;
}

} // namespace

int main() {
    const auto bundle = assets::empty_fixtures::bundle();
    bool ok = expect(assets::empty_fixtures::kAssetCount == 0, "generated count is zero") &&
              expect(assets::empty_fixtures::kAssetBytes == 0, "generated byte total is zero") &&
              expect(bundle.empty() && bundle.size() == 0 && bundle.byte_size() == 0,
                     "an empty bundle reports no entries or bytes");
    const auto missing = bundle.find("icons/anything.svg");
    ok = expect(!missing.has_value() && missing.error() == assets::AssetError::not_found,
                "an empty bundle misses every name") &&
         expect(!bundle.contains("icons/anything.svg"), "contains() is false on an empty bundle") &&
         expect(bundle.find("../escape.svg").error() == assets::AssetError::invalid_name,
                "invalid names are still invalid_name on an empty bundle") &&
         ok;
    if (!ok) {
        std::cerr << "asset_zero_bundle: FAILED\n";
        return 1;
    }
    std::cout << "asset_zero_bundle: ok\n";
    return 0;
}
