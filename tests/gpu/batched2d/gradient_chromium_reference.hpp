//
// Each series holds 23 packed 0xRRGGBB samples at x (or y) = 10, 12, ... 54: along row 32, along
// column 32 and along the main diagonal (x = y). The first six scenes are the ones the mask test
// (layer_mask_chromium_reference.hpp) measured on a four-pixel grid; the rest add an oblique linear
// ramp, closest-side and farthest-corner radials, a hard-edged and a smooth conic with `from` and
// an off-centre position, repeating linear and radial ramps, and translucent ramps over black.

