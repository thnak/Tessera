// Per-component header emission (struct fields and method declarations).

#include "codegen_internal.hpp"
#include "emit_controlled.hpp"
#include "emit_events.hpp"
#include "interpolation.hpp"

#include <optional>
#include <string>
#include <string_view>
#include <utility>
#include <vector>

namespace tessera::compiler::codegen::internal {
namespace {

bool fail(std::string& error, std::string message) {
    error = "TESSERA_CODEGEN_UNSUPPORTED: " + std::move(message);
    return false;
}

} // namespace
bool emit_component_header(const ir::Component& component, std::string_view ns,
                           const std::vector<const ir::Binding*>& bindings,
                           const std::vector<DynamicText>& dynamic_text,
                           const std::vector<DynamicMetadata>& dynamic_metadata,
                           const std::vector<ControlledInput>& controlled_inputs,
                           GeneratedFile& file, std::string& error) {
    CppWriter writer;
    writer.line("// SPDX-License-Identifier: MIT");
    writer.line("// Generated by Tessera codegen from the IR; see docs/design/codegen.md.");
    writer.line("// Developer code belongs only inside [DEVELOPER_LOGIC_START/END] regions.");
    writer.line("#pragma once");
    writer.line("");
    writer.line("#include \"tessera/ui/scene/component_lifecycle.hpp\"");
    writer.line("#include \"tessera/ui/scene/event_payloads.hpp\"");
    if (!controlled_inputs.empty()) {
        writer.line("#include \"tessera/ui/text/text_input_runtime.hpp\"");
    }
    writer.line("#include \"tessera/ui/scene/node.hpp\"");
    writer.line("");
    writer.line("#include <cstdint>");
    writer.line("#include <memory>");
    writer.line("#include <optional>");
    writer.line("#include <string>");
    writer.line("#include <string_view>");
    writer.line("#include <vector>");
    writer.line("");
    writer.open("namespace " + std::string(ns));
    writer.open("namespace gen");
    writer.line("// " + component.id + " (" + component.name + ").");
    writer.open("struct " + component.name);
    for (const ir::State& state : component.state) {
        const std::optional<std::string> type = cpp_type(state.type);
        if (!type) {
            return fail(error, "state `" + state.name + "` has a type with no C++ form (`" +
                                   state.type + "`)");
        }
        ExprEmission initial =
            state.initial ? emit_expr(*state.initial, component) : ExprEmission{"{}", {}};
        if (!initial.error.empty()) {
            return fail(error, initial.error);
        }
        writer.line("// useState `" + state.name + "`.");
        writer.line(*type + " " + member_name(state.id) + " = " + initial.text + ";");
    }
    for (const ir::Ref& ref : component.refs) {
        writer.line("// useRef `" + ref.name + "` (assigned in build() to its target node).");
        writer.line("tessera::ui::Node* " + member_name(ref.id) + " = nullptr;");
    }
    for (const ir::AnimatedValue& value : component.animated_values) {
        const std::optional<std::string> type = cpp_type(value.type);
        if (!type) {
            return fail(error, "animated value `" + value.name + "` has a type with no C++ form");
        }
        ExprEmission initial =
            value.initial ? emit_expr(*value.initial, component) : ExprEmission{"{}", {}};
        if (!initial.error.empty()) {
            return fail(error, initial.error);
        }
        writer.line("// useAnimatedValue `" + value.name +
                    "` (a plain field until the animation controller API exists).");
        writer.line(*type + " " + member_name(value.id) + " = " + initial.text + ";");
    }
    for (const DynamicText& entry : dynamic_text) {
        const std::string suffix = std::to_string(entry.ordinal);
        writer.line("// Interpolated text for the node with pre-order index " + suffix +
                    " (PaintData only; never a layout input).");
        writer.line("tessera::ui::Node* text_node_" + suffix + "_ = nullptr;");
        writer.line("std::string text_node_" + suffix + "_value_;");
        writer.line("std::uint64_t text_node_" + suffix + "_hash_ = 0;");
        writer.line("bool text_node_" + suffix + "_set_ = false;");
    }
    for (const DynamicMetadata& entry : dynamic_metadata) {
        const std::string base = metadata_member(entry);
        writer.line("// Interpolated `" + entry.name +
                    "` metadata; the component owns the string, the node borrows it.");
        writer.line("tessera::ui::Node* " + base + "_node_ = nullptr;");
        writer.line("std::string " + base + "_value_;");
        writer.line("std::uint64_t " + base + "_hash_ = 0;");
        writer.line("bool " + base + "_set_ = false;");
    }
    emit_controlled_fields(writer, controlled_inputs);
    for (const ir::Effect& effect : component.effects) {
        writer.line("// useEffect `" + effect.id +
                    "` state (deps hash, run counter, active flag).");
        writer.line("tessera::ui::EffectState " + member_name(effect.id) + "state_;");
    }
    for (const ir::Prop& prop : component.props) {
        const std::optional<std::string> type = cpp_type(prop.type);
        if (!type) {
            return fail(error, "prop `" + prop.name + "` has a type with no C++ form (`" +
                                   prop.type + "`)");
        }
        std::string initial = "{}";
        if (prop.default_value) {
            ExprEmission value = emit_expr(*prop.default_value, component);
            if (!value.error.empty()) {
                return fail(error, value.error);
            }
            initial = "{" + value.text + "}";
        }
        writer.line("// prop `" + prop.name + "`.");
        writer.line(*type + " " + member_name("prop::" + prop.name) + " = " + initial + ";");
    }
    writer.line("");
    writer.line("void build(tessera::ui::Node& parent);");
    writer.line("// Lifecycle: mount() runs effects once; update_effects() re-runs changed deps;");
    writer.line("// unmount() runs cleanups in reverse declaration order.");
    writer.line("void mount();");
    writer.line("void update_effects();");
    writer.line("void unmount();");
    writer.line("");
    writer.line("// Recompute interpolated values; marks Paint|Render only when a value changed.");
    writer.line("void apply_state();");
    writer.line("// Host entry after event dispatch: update_effects() then apply_state().");
    writer.line("void update();");
    for (const ir::Handler& handler : component.handlers) {
        bool typed = false;
        std::string param_name;
        const std::optional<std::string> signature =
            payload_signature(handler.params, typed, param_name);
        if (!signature) {
            return fail(error, "handler `" + handler.id + "` has an unsupported payload record");
        }
        writer.line("void " + method_name(handler.id) + "(" + *signature + ");");
    }
    for (const ir::Binding* binding : bindings) {
        if (binding->kind == ir::BindingKind::Event) {
            bool typed = false;
            std::string param_name;
            const std::optional<std::string> signature =
                payload_signature(binding->params, typed, param_name);
            if (!signature) {
                return fail(error,
                            "binding `" + binding->id + "` has an unsupported payload record");
            }
            writer.line("void " + binding->region + "(" + *signature + ");");
            continue;
        }
        std::string return_type;
        if (!binding->return_type.empty()) {
            return_type = handler_type(binding->return_type);
            if (return_type.empty()) {
                return fail(error, "binding `" + binding->id +
                                       "` has an unsupported return type `" + binding->return_type +
                                       "`");
            }
        }
        writer.line(std::string(return_type.empty() ? "void" : return_type) + " " +
                    binding->region + "();");
    }
    writer.close(";");
    writer.close("");
    writer.close("");
    file.path = component.name + ".hpp";
    file.text = std::move(writer.text);
    return true;
}

} // namespace tessera::compiler::codegen::internal