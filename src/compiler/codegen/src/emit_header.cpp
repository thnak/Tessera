bool fail(std::string& error, std::string message) {
    error = "TESSERA_CODEGEN_UNSUPPORTED: " + std::move(message);
    return false;
}

// An IR array initial only has a C++ form as a braced list for a `std::vector<T>` (list-typed)
// field; guarding here keeps a malformed IR from emitting initializer text that cannot compile.
bool is_list_cpp_type(std::string_view cpp) {
    return cpp.rfind("std::vector<", 0) == 0;
}

bool uses_focus_actions(const ir::Component& component) {
    for (const ir::Handler& handler : component.handlers) {
        for (const ir::Action& action : handler.actions) {
            if (action.kind == ir::ActionKind::Focus || action.kind == ir::ActionKind::Blur) {
                return true;
            }
        }
    }
    return false;
}

