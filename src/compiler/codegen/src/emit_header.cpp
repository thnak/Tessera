bool emit_component_header(const ir::Component& component, const ir::IrModule& module,
                           const std::vector<const ir::Binding*>& bindings,
                           const std::vector<DynamicText>& dynamic_text,
                           const std::vector<DynamicMetadata>& dynamic_metadata,
                           const std::vector<ControlledInput>& controlled_inputs,
                           const DynamicPlan& plan, const FormPlan& forms,
                           const std::vector<ComponentInstance>& instances, GeneratedFile& file,
                           std::string& error) {
    const std::string ns = module.name;
    const std::vector<std::string> includes = component_includes(module, component);
    bool has_props = false;
    bool has_callback_props = false;
    for (const ComponentInstance& instance : instances) {
        has_props = has_props || !instance.props.empty();
        for (const PropBinding& binding : instance.props) {
            has_callback_props = has_callback_props || binding.is_callback();
        }
    }
    for (const ir::Prop& prop : component.props) {
        if (prop.type != "children" && !is_value_prop_type(prop.type, module.types)) {
            has_callback_props = has_callback_props || !callback_prop_type(prop.type).empty();
        }
    }
    CppWriter writer;
    writer.line("// SPDX-License-Identifier: MIT");
    writer.line("// Generated by Tessera codegen from the IR; see docs/design/codegen.md.");
    writer.line(
        "// ADR-040: reshaped into the generated base; the developer class owns the bindings.");
    writer.line("#pragma once");
    writer.line("");
    writer.line("#include \"tessera/ui/scene/component_lifecycle.hpp\"");
    writer.line("#include \"tessera/ui/scene/update_scheduler.hpp\"");
    writer.line("#include \"tessera/ui/scene/dirty_mask.hpp\"");
    if (!component.animated_values.empty()) {
        writer.line("#include \"tessera/ui/animation/animated_scalar.hpp\"");
    }
    writer.line("#include \"tessera/ui/scene/event_payloads.hpp\"");
    writer.line("#include \"tessera/ui/scene/state_snapshot.hpp\"");
    if (!controlled_inputs.empty()) {
        writer.line("#include \"tessera/ui/text/text_input_runtime.hpp\"");
    }
    writer.line("#include \"tessera/ui/scene/node.hpp\"");
    if (!instances.empty()) {
        writer.line("#include \"tessera/ui/scene/node_ids.hpp\"");
    }
    if (plan.has_virtual) {
        writer.line("#include \"tessera/ui/virtual/item_geometry.hpp\"");
    }
    for (const std::string& include : includes) {
        writer.line("#include \"" + include + ".hpp\"");
    }
    // ADR-051 slice 4: a component that names a declared record includes the module's aggregate
    // struct header. A module without records emits no such file, so no existing golden gains a
    // line.
    if (uses_record_types(component, module)) {
        writer.line("#include \"" + module.name + "_types.hpp\"");
    }
    // ADR-050 section 3.1 (AF5): a component that declares a `useService` requirement includes the
    // runtime seam and the project headers that name its service interfaces. Emitted only then, so
    // a component without a requirement gains no include line.
    if (uses_services(component)) {
        writer.line("#include \"tessera/appfw/service_context.hpp\"");
        for (const std::string& header : service_headers(component)) {
            writer.line("#include \"" + header + "\"");
        }
    }
    emit_form_includes(writer, forms);
    // ADR-067 spike #661 (off by default): the pending-UI model, emitted only for a component that
    // has a `Suspense` node or a transition-marked action.
    for (const std::string& header : pending_headers(component, plan)) {
        writer.line("#include \"" + header + "\"");
    }
    if (uses_focus_actions(component)) {
        writer.line("#include \"tessera/ui/scene/focus.hpp\"");
    }
    // ADR-064 item 7: the behavior seam. A component with behaviors needs the instance, the
    // registry and the router it attaches through; a component without them includes nothing.
    if (uses_behaviors(component)) {
        writer.line("#include \"tessera/ui/behavior/instance.hpp\"");
        writer.line("#include \"tessera/ui/behavior/registry.hpp\"");
        writer.line("#include \"tessera/ui/scene/input_dispatch.hpp\"");
    }
    const bool observes = observes_size(component, module);
    if (observes) {
        writer.line("#include \"tessera/ui/layout/layout_observer.hpp\"");
    }
    // `environment` hook values (issue #692): the consumer set the host pushes a new class through.
    if (has_environment(component)) {
        writer.line("#include \"tessera/ui/responsive/environment_set.hpp\"");
        // A `useMediaQuery` hook parses and evaluates its query with the stylesheet's own evaluator
        // (issue #631), so the base needs the matcher and the media context.
        for (const ir::Environment& env : component.environment) {
            if (env.provider == "media_query") {
                writer.line("#include \"tessera/ui/responsive/media_query_match.hpp\"");
                break;
            }
        }
    }
    writer.line("");
    writer.line("#include <cstdint>");
    if (plan.has_lists) {
        writer.line("#include <array>");
        writer.line("#include <cstddef>");
    }
    if (has_callback_props) {
        writer.line("#include <functional>");
    }
    writer.line("#include <memory>");
    writer.line("#include <optional>");
    writer.line("#include <string>");
    writer.line("#include <string_view>");
    if (uses_services(component)) {
        writer.line("#include <tuple>");
    }
    writer.line("#include <vector>");
    writer.line("");
    writer.open("namespace " + ns);
    writer.open("namespace gen");
    writer.line("// " + component.id + " (" + component.name + ").");
    emit_dynamic_item_structs(writer, plan, instances);
    writer.open("struct " + component.name);
    writer.line(
        "// Added to every NodeId this component builds. The owner sets it before build() so each");
    writer.line("// instance owns distinct ids (issue #295); a root component keeps 0.");
    writer.line("tessera::ui::NodeId node_id_base_ = 0;");
    // Props come first: a state/animated initializer may read one (IR allows it), and a
    // member initializer can only name a member declared before it.
    for (const ir::Prop& prop : component.props) {
        if (prop.type == "children") {
            continue; // the static slot declaration is not a generated field (ir-v1 section 3.4)
        }
        std::optional<std::string> type = cpp_type(prop.type, module.types);
        if (!type) {
            // A record-typed prop is a callback prop: it is bound through the node's events and
            // stored as a generated callable (docs/specs/component-model-v1.md section 3).
            const std::string callback = callback_prop_type(prop.type);
            if (!callback.empty()) {
                type = callback;
            }
        }
        if (!type) {
            return fail(error, "prop `" + prop.name + "` has a type with no C++ form (`" +
                                   prop.type + "`)");
        }
        if (!is_value_prop_type(prop.type, module.types) && prop.default_value) {
            return fail(error, "callback prop `" + prop.name + "` has no default value");
        }
        std::string initial = "{}";
        if (prop.default_value && is_value_prop_type(prop.type, module.types)) {
            if (prop.default_value->kind == ir::ExprKind::Array && !is_list_cpp_type(*type)) {
                return fail(error, "prop `" + prop.name +
                                       "` has an array default but its type is not a list");
            }
            ExprEmission value = emit_initializer_expr(*prop.default_value, component);
            if (!value.error.empty()) {
                return fail(error, value.error);
            }
            // An array default and a record value already carry their braces; a scalar default is
            // brace-initialized.
            const bool braced = prop.default_value->kind == ir::ExprKind::Array ||
                                prop.default_value->kind == ir::ExprKind::Record;
            initial = braced ? value.text : "{" + value.text + "}";
        }
        writer.line("// prop `" + prop.name + "`.");
        writer.line(*type + " " + member_name("prop::" + prop.name) + " = " + initial + ";");
    }
    for (const ir::State& state : component.state) {
        const std::optional<std::string> type = cpp_type(state.type, module.types);
        if (!type) {
            return fail(error, "state `" + state.name + "` has a type with no C++ form (`" +
                                   state.type + "`)");
        }
        if (state.initial && state.initial->kind == ir::ExprKind::Array &&
            !is_list_cpp_type(*type)) {
            return fail(error, "state `" + state.name + "` has an array initial but its type `" +
                                   state.type + "` is not a list");
        }
        ExprEmission initial = state.initial ? emit_initializer_expr(*state.initial, component)
                                             : ExprEmission{"{}", {}};
        if (!initial.error.empty()) {
            return fail(error, initial.error);
        }
        writer.line("// useState `" + state.name + "`.");
        writer.line(*type + " " + member_name(state.id) + " = " + initial.text + ";");
    }
    for (const ir::Ref& ref : component.refs) {
        writer.line("// useRef `" + ref.name + "` (assigned in build() to its target node).");
        writer.line("tessera::ui::Node* " + member_name(ref.id) + " = nullptr;");
    }
    for (const ir::AnimatedValue& value : component.animated_values) {
        const std::optional<std::string> type = cpp_type(value.type, module.types);
        if (!type) {
            return fail(error, "animated value `" + value.name + "` has a type with no C++ form");
        }
        ExprEmission initial = value.initial ? emit_initializer_expr(*value.initial, component)
                                             : ExprEmission{"{}", {}};
        if (!initial.error.empty()) {
            return fail(error, initial.error);
        }
        writer.line("// useAnimatedValue `" + value.name +
                    "`: the sampled value every read uses, and its controller (ticked by the");
        writer.line("// host's UpdateScheduler; see tick_animations).");
        writer.line(*type + " " + member_name(value.id) + " = " + initial.text + ";");
        writer.line("tessera::ui::animation::AnimatedScalar " + animated_controller_name(value.id) +
                    "{" + member_name(value.id) + "};");
        if (animated_has_completion(component, value.id)) {
            writer.line("// 1-based index of the handler the current set runs when it completes (0 "
                        "= none).");
            writer.line("int " + animated_on_complete_name(value.id) + " = 0;");
        }
    }
    for (const ComponentInstance& instance : instances) {
        if (instance.in_template()) {
            continue; // owned per item by the keyed item record, not by a caller member
        }
        writer.line("// Component instance `" + instance.component_id +
                    "` for the node with pre-order index " + std::to_string(instance.ordinal) +
                    " (the instance owns its own state).");
        writer.line(instance.type_name + " " + instance_member(instance.ordinal) + ";");
        for (const PropBinding& binding : instance.props) {
            // apply_props() guards every assignment: a value prop stores its last FNV-1a hash and a
            // callback prop a one-shot bound flag (docs/design/compiler.md section 11).
            if (binding.is_callback()) {
                writer.line("bool " + prop_bound_member(instance.ordinal, binding.name) +
                            " = false;");
            } else if (prop_guard(binding.type) == PropGuard::Value) {
                writer.line("std::uint64_t " + prop_guard_member(instance.ordinal, binding.name) +
                            " = 0;");
            }
        }
    }
    for (const DynamicText& entry : dynamic_text) {
        const std::string suffix = std::to_string(entry.ordinal);
        writer.line("// Interpolated text for the node with pre-order index " + suffix +
                    " (PaintData only; never a layout input).");
        writer.line("tessera::ui::Node* text_node_" + suffix + "_ = nullptr;");
        writer.line("std::string text_node_" + suffix + "_value_;");
        writer.line("std::uint64_t text_node_" + suffix + "_hash_ = 0;");
        writer.line("bool text_node_" + suffix + "_set_ = false;");
    }
    for (const DynamicMetadata& entry : dynamic_metadata) {
        const std::string base = metadata_member(entry);
        writer.line("// Interpolated `" + entry.name +
                    "` metadata; the component owns the string, the node borrows it.");
        writer.line("tessera::ui::Node* " + base + "_node_ = nullptr;");
        writer.line("std::string " + base + "_value_;");
        writer.line("std::uint64_t " + base + "_hash_ = 0;");
        writer.line("bool " + base + "_set_ = false;");
    }
    emit_controlled_fields(writer, controlled_inputs);
    for (const ir::Effect& effect : component.effects) {
        writer.line("// useEffect `" + effect.id +
                    "` state (deps hash, run counter, active flag).");
        writer.line("tessera::ui::EffectState " + member_name(effect.id) + "state_;");
    }
    // ADR-050 section 3.1 (AF5): the private typed slot of a component that declares a
    // `useService` requirement. Emitted with the other fields so `apply_access` keeps it private.
    if (!emit_behavior_fields(writer, component, error)) {
        return false;
    }
    if (!emit_service_fields(writer, component, error)) {
        return false;
    }
    writer.line("");
    emit_dynamic_fields(writer, plan);
    emit_pending_fields(writer, component, plan);
    emit_form_declarations(writer, forms);
    if (uses_focus_actions(component)) {
        writer.line(
            "// `ref.focus()` / `ref.blur()` (issue #226) act through the host's FocusManager.");
        writer.line("tessera::ui::FocusManager* focus_manager_ = nullptr;");
        writer.line("void set_focus_manager(tessera::ui::FocusManager* manager) {");
        writer.line("    focus_manager_ = manager;");
        writer.line("}");
    }
    writer.line("void build(tessera::ui::Node& parent);");
    if (component_takes_children(component)) {
        writer.line(
            "// Callee side of the static children slot: `slot` is the caller's content and");
        writer.line("// is attached where this component places its Slot (ir-v1.md section 3.4).");
        writer.line("void build(tessera::ui::Node& parent, "
                    "std::vector<std::unique_ptr<tessera::ui::Node>> slot);");
    }
    writer.line("// Lifecycle: mount() runs effects once; update_effects() re-runs changed deps;");
    writer.line("// unmount() runs cleanups in reverse declaration order.");
    writer.line("void mount();");
    writer.line("void update_effects();");
    writer.line("void unmount();");
    if (uses_behaviors(component)) {
        // The behavior seam (ADR-064 item 7, behavior-hooks-v1.md section 9). The owner calls
        // attach_behaviors() once the tree is built, refresh_behaviors() after an input dispatch,
        // and detach_behaviors() before the tree goes away. Without these the slots would never be
        // attached, which is the defect #641 fixes.
        writer.line("// ADR-064 item 7: attach every behavior hook of this component. Call once");
        writer.line("// after build(), when every target ref holds its node.");
        writer.line("void attach_behaviors(tessera::ui::InputRouter& router);");
        writer.line("// Recompute the behavior outputs from the scene's interaction state. Call");
        writer.line("// after an input dispatch; it does not consult the options hash.");
        writer.line("void refresh_behaviors();");
        writer.line("// Detach every behavior in reverse declaration order. Idempotent.");
        writer.line("void detach_behaviors();");
    }
    writer.line("");
    writer.line("// Recompute interpolated values; marks Paint|Render only when a value changed.");
    writer.line("void apply_state();");
    if (has_props) {
        writer.line(
            "// Refresh the declared props of the component instances this component owns.");
        writer.line("void apply_props();");
    }
    writer.line(
        "// A hand call: marks every cell dirty, then runs flush_update() (headless tests).");
    writer.line("void update();");
    writer.line("// Runs update_effects() then apply_state() over the dirty cells; the scheduler "
                "calls it.");
    writer.line("void flush_update();");
    emit_dirty_declarations(writer, plan.dirty);
    if (!emit_schedule_declarations(writer, module, component, error)) {
        return false;
    }
    // `environment` hook values (docs/specs/jsx-subset-v1.md section 7.1, issue #692): the fields
    // and the host-facing setters. Emitted only for a component that reads one, so every other
    // component's base is byte-identical.
    emit_environment_declarations(writer, component, module);
    emit_snapshot_declaration(writer);
    if (observes) {
        std::vector<EventAdapter> observed;
        unsigned ordinal = 0;
        if (!collect_event_adapters(component.root, component, bindings, controlled_inputs, ordinal,
                                    observed, error)) {
            return false;
        }
        emit_size_observation_declarations(writer, component, module, observed);
    }
    if (!plan.groups.empty() || !plan.lists.empty()) {
        emit_dynamic_declarations(writer, plan);
    }
    emit_pending_declarations(writer, component, plan);
    for (const ir::Handler& handler : component.handlers) {
        bool typed = false;
        std::string param_name;
        const std::optional<std::string> signature =
            payload_signature(handler.params, typed, param_name);
        if (!signature) {
            return fail(error, "handler `" + handler.id + "` has an unsupported payload record");
        }
        writer.line("void " + method_name(handler.id) + "(" + *signature + ");");
    }
    // ADR-040: the bindings are dispatch thunks into the developer class, not declarations.
    if (!emit_base_members(writer, module, component, bindings, instances, error)) {
        return false;
    }
    writer.close(";");
    writer.close("");
    writer.close("");
    file.path = component.name + ".hpp";
    file.text = std::move(writer.text);
    return true;
}

