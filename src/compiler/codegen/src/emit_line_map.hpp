// `#line` mapping of generated C++ back to the TSX it came from (issue #78). The generated base is
// one header whose text the ADR-040 reshaping rewrites line by line (`emit_base.cpp`), so a
// directive cannot be spliced in by the emitters: the reshaping re-indents bodies, prefixes
// `inline`/`static` and replaces identifiers, and it would treat a directive as ordinary text.
//
// The reshaping therefore inserts a *marker* comment around each mapped statement and records the
// TSX span in a side table the marker names by index, and `apply_line_map` resolves every marker
// into directives once the final text exists. Two properties follow:
//
//   * a marker never contains a file path, so no reshaping rule can rewrite it, and the path only
//     appears in text the reshaping has already finished with;
//   * the mapping is scoped to the generated base alone. Nothing is emitted into, or across an
//     `#include` of, the developer-owned `<Component>.hpp`/`.cpp` (ADR-040): a directive that
//     leaked into a developer file would remap the developer's own code to TSX coordinates, which
//     is worse than no mapping at all.
//
// With no markers (the default, `CodegenOptions::line_directives == false`) the emitter adds no
// marker line, so the generated bytes are unchanged and the committed goldens do not move.

#pragma once

#include "tessera/compiler/ir/source_span.hpp"

#include <cstddef>
#include <cstdint>
#include <string>
#include <string_view>
#include <vector>

namespace tessera::compiler::codegen::internal {

// The TSX spans of one generated file, indexed by the markers the reshaping wrote into it.
struct LineMapMarkers {
    std::vector<ir::SourceSpan> spans;

    // Records `span` and returns the index a marker line names.
    std::size_t add(const ir::SourceSpan& span) {
        spans.push_back(span);
        return spans.size() - 1;
    }
};

// Marker spellings. A begin marker is `//@tessera-line <index>`; the end marker carries no index
// because the mapped regions of one file never nest.
inline constexpr std::string_view kLineMapEnd = "//@tessera-line-end";

// True when `span` can become a directive: `#line` needs a file name without a quote or newline and
// a 1-based line number, and a span with no location must not invent a position
// (docs/specs/compiler-diagnostics-v1.md section 3).
[[nodiscard]] bool line_map_usable(const ir::SourceSpan& span);

// `//@tessera-line <index>`, the line the reshaping writes before a mapped statement.
[[nodiscard]] std::string marker_line(std::size_t index);

// `#line 42 "ui/App.tsx"`. Never ends in a backslash: a trailing backslash would splice the next
// generated line into the directive (a `//` comment ending in one is `-Werror=comment` on GCC).
[[nodiscard]] std::string line_directive(std::uint32_t line, std::string_view file);

// Resolves the markers of a finished generated file into directives:
//
//     //@tessera-line 0
//     static_assert(...);
//     //@tessera-line-end
//     ...
//
// becomes
//
//     #line 4 "ui/Counter.tsx"
//     static_assert(...);
//     #line 118 "Sample.g.hpp"
//     ...
//
// The restoring directive is written at the exact physical line it resumes on, so the numbering of
// the *generated* file is identity everywhere outside a mapped region: an error in unmapped
// generated code still points at its own line of the `.g.hpp` and does not drift by the number of
// directives emitted above it. That invariant is what keeps the second error in a file as accurate
// as the first, and what the test asserts.
//
// A marker naming no usable span emits nothing, so a malformed IR cannot produce a directive
// pointing at an invented location. No marker text survives in the result.
[[nodiscard]] std::string apply_line_map(std::string_view generated_name, std::string_view text,
                                         const LineMapMarkers& markers);

} // namespace tessera::compiler::codegen::internal
