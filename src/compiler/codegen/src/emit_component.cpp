bool emit_component(const ir::Component& component, const ir::IrModule& module,
                    std::vector<GeneratedFile>& files, std::string& error, bool base_mode) {
    if (component.name.empty()) {
        return fail(error, "a component has no name");
    }
    if (component.environment.size() != 0) {
        return fail(error, "component `" + component.name +
                               "` uses library hooks (`environment`), which are a later slice");
    }
    const std::vector<const ir::Binding*> owned = component_bindings(component, module.bindings);
    // Component composition first: it validates the instance forms and is needed by both files.
    std::vector<ComponentInstance> instances;
    if (!collect_component_instances(module, component, instances, error)) {
        return false;
    }
    // The dynamic plan next: it is the authoritative validation of conditional/list forms, so its
    // diagnostics win over the per-collector checks below.
    DynamicPlan plan;
    if (!collect_dynamic_plan(component, plan, error)) {
        return false;
    }
    // The collection-level events of every virtual collection in the plan (onScroll/onEndReached):
    // resolved here so a failing form reports one deterministic error before any file is emitted.
    if (!collect_virtual_events(component, owned, plan, error)) {
        return false;
    }
    // The generated form-state binding of any library `Form` this component owns
    // (form_binding.hpp).
    FormPlan forms;
    if (!collect_form_plan(module, component, forms, error)) {
        return false;
    }
    unsigned ordinal = 0;
    std::vector<DynamicText> dynamic_text;
    if (!collect_dynamic_text(component.root, component, ordinal, dynamic_text, error)) {
        return false;
    }
    ordinal = 0;
    std::vector<DynamicMetadata> dynamic_metadata;
    if (!collect_dynamic_metadata(component.root, component, ordinal, dynamic_metadata, error)) {
        return false;
    }
    ordinal = 0;
    std::vector<ControlledInput> controlled_inputs;
    if (!collect_controlled_inputs(component.root, component, owned, ordinal, controlled_inputs,
                                   error)) {
        return false;
    }
    GeneratedFile header;
    if (!emit_component_header(component, module, owned, dynamic_text, dynamic_metadata,
                               controlled_inputs, plan, forms, instances, header, error,
                               base_mode)) {
        return false;
    }
    GeneratedFile source;
    if (!emit_source(component, module, owned, dynamic_text, dynamic_metadata, controlled_inputs,
                     plan, forms, instances, source, error, base_mode)) {
        return false;
    }
    if (base_mode) {
        GeneratedFile generated;
        if (!emit_generated_base(component, owned, header.text, source.text, generated, error)) {
            return false;
        }
        files.push_back(std::move(generated));
        return true;
    }
    files.push_back(std::move(header));
    files.push_back(std::move(source));
    return true;
}

