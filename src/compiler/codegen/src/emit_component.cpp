bool fail(std::string& error, std::string message) {
    error = "TESSERA_CODEGEN_UNSUPPORTED: " + std::move(message);
    return false;
}

std::vector<const ir::Binding*> component_bindings(const ir::Component& component,
                                                   const std::vector<ir::Binding>& bindings) {
    std::vector<const ir::Binding*> result;
    for (const ir::Binding& binding : bindings) {
        if (binding.component == component.id) {
            result.push_back(&binding);
        }
    }
    return result;
}

// True when the component places its `children` slot somewhere in the tree.
bool tree_has_slot(const ir::Node& node) {
    if (node.kind == ir::NodeKind::Slot) {
        return true;
    }
    for (const ir::Node& child : node.children) {
        if (tree_has_slot(child)) {
            return true;
        }
    }
    if (node.fallback && tree_has_slot(*node.fallback)) {
        return true;
    }
    return node.item_template && tree_has_slot(*node.item_template);
}

bool emit_stub_body(CppWriter& writer, const ir::Binding& binding,
                    std::string_view event_parameter) {
    writer.line("// TODO(tessera-codegen): implement the developer body for " + binding.id + ".");
    if (!event_parameter.empty()) {
        writer.line("(void)" + std::string(event_parameter) + ";");
    }
    if (!binding.return_type.empty()) {
        writer.line("return {};");
    }
    return true;
}

bool emit_source(const ir::Component& component, const ir::IrModule& module,
                 const std::vector<const ir::Binding*>& bindings,
                 const std::vector<DynamicText>& dynamic_text,
                 const std::vector<DynamicMetadata>& dynamic_metadata,
                 const std::vector<ControlledInput>& controlled_inputs, const DynamicPlan& plan,
                 const FormPlan& forms, const std::vector<ComponentInstance>& instances,
                 GeneratedFile& file, std::string& error, bool base_mode) {
    const bool has_interpolation = !dynamic_text.empty() || !dynamic_metadata.empty();
    bool has_props = false;
    bool has_callbacks = false;
    for (const ComponentInstance& instance : instances) {
        has_props = has_props || !instance.props.empty();
        for (const PropBinding& binding : instance.props) {
            has_callbacks = has_callbacks || binding.is_callback();
        }
    }
    const bool has_update = has_interpolation || !plan.groups.empty() || has_props;
    const bool takes_children = component_takes_children(component);
    const bool has_slot = tree_has_slot(component.root);
    const std::string ns = module.name;
    CppWriter writer;
    writer.line("// SPDX-License-Identifier: MIT");
    writer.line("// Generated by Tessera codegen from the IR; see docs/design/codegen.md.");
    writer.line("// Developer code belongs only inside [DEVELOPER_LOGIC_START/END] regions.");
    writer.line("#include \"" + component.name + ".hpp\"");
    writer.line("");
    writer.line("#include <memory>");
    writer.line("#include <utility>");
    if (takes_children || has_props || plan.has_lists) {
        writer.line("#include <vector>");
    }
    if (has_props) {
        writer.line("#include <string>");
    }
    if (has_callbacks) {
        writer.line("#include <functional>");
    }
    if (has_interpolation || plan.has_lists) {
        writer.line("#include <charconv>");
        writer.line("#include <cstdint>");
        writer.line("#include <string>");
        writer.line("#include <string_view>");
    }
    if (plan.has_lists) {
        writer.line("#include <array>");
        writer.line("#include <cstddef>");
    }
    if (plan.has_virtual) {
        writer.line("#include \"tessera/ui/virtual/scroll_anchor.hpp\"");
    }
    writer.line("");
    writer.open("namespace " + ns);
    writer.open("namespace gen");
    writer.line("");
    if (has_interpolation || plan.has_lists) {
        emit_format_helpers(writer);
    }
    emit_dynamic_helpers(writer, plan);
    (void)instances;
    unsigned ordinal = 0;
    std::vector<EventAdapter> adapters;
    if (!collect_event_adapters(component.root, component, bindings, controlled_inputs, ordinal,
                                adapters, error)) {
        return false;
    }
    emit_event_adapters(writer, component.name, adapters);
    emit_controlled_adapters(writer, component.name, controlled_inputs);
    emit_form_adapters(writer, component, forms);
    if (takes_children) {
        writer.open("void " + component.name + "::build(tessera::ui::Node& parent)");
        writer.line("build(parent, {});");
        writer.close("");
        writer.line("");
        writer.open("void " + component.name +
                    "::build(tessera::ui::Node& parent, "
                    "std::vector<std::unique_ptr<tessera::ui::Node>> slot)");
    } else {
        writer.open("void " + component.name + "::build(tessera::ui::Node& parent)");
    }
    if (takes_children && !has_slot) {
        writer.line("(void)slot; // the component declares `children` but places no Slot");
    }
    if (has_props) {
        // The declared props of every owned instance are assigned before any child build() runs, so
        // the callee's build reads its prop members (docs/specs/component-model-v1.md section 3).
        writer.line("apply_props();");
    }
    // Seed the form controller and resolve the Field props before any slot content is built.
    emit_form_build_calls(writer, forms);
    NodeEmitState state{component,        adapters,          dynamic_text,
                        dynamic_metadata, controlled_inputs, &plan};
    state.module = &module;
    state.forms = &forms;
    state.slot_variable = takes_children ? "slot" : std::string();
    std::string root_variable;
    if (!emit_node(writer, component.root, state, root_variable, error)) {
        return false;
    }
    writer.line("parent.add_child(std::move(" + root_variable + "));");
    if (has_update) {
        writer.line("apply_state();");
    }
    writer.close("");
    writer.line("");
    if (!emit_apply_props(writer, component, instances, error)) {
        return false;
    }
    if (!emit_form_source(writer, component, forms, error)) {
        return false;
    }
    if (has_update) {
        if (!emit_apply_state(writer, component, dynamic_text, dynamic_metadata, controlled_inputs,
                              plan, forms, has_props, error)) {
            return false;
        }
    } else {
        writer.open("void " + component.name + "::apply_state()");
        writer.close("");
        writer.line("");
    }
    if (!emit_dynamic_sources(writer, component, module, plan, adapters, dynamic_text,
                              dynamic_metadata, controlled_inputs, instances, error)) {
        return false;
    }
    if (!emit_lifecycle(component, bindings, instances, plan, writer, error)) {
        return false;
    }
    if (!emit_schedule_definitions(writer, component, instances, plan, error)) {
        return false;
    }
    emit_snapshot_definition(writer, component);
    emit_size_observation_definitions(writer, component, module, adapters, instances);
    emit_controlled_accessors(writer, component, controlled_inputs);
    for (const ir::Handler& handler : component.handlers) {
        bool typed = false;
        std::string param_name;
        const std::optional<std::string> signature =
            payload_signature(handler.params, typed, param_name);
        if (!signature) {
            return fail(error, "handler `" + handler.id + "` has an unsupported payload record");
        }
        const std::string name = method_name(handler.id);
        writer.open("void " + component.name + "::" + name + "(" + *signature + ")");
        writer.line("(void)" + param_name + ";");
        std::string action_error;
        const std::optional<std::string> body =
            emit_actions(handler.actions, component, handler.params, action_error);
        if (!body) {
            return fail(error, action_error);
        }

        std::string_view rest = *body;
        while (!rest.empty()) {
            const std::size_t newline = rest.find('\n');
            const std::string_view line = rest.substr(0, newline);
            if (!line.empty()) {
                writer.line(line);
            }
            if (newline == std::string_view::npos) {
                break;
            }
            rest = rest.substr(newline + 1);
        }
        if (has_update) {
            writer.line("apply_state();");
        }
        writer.close("");
        writer.line("");
    }
    for (const ir::Binding* binding : bindings) {
        if (base_mode) {
            break; // ADR-040: the developer class owns every binding body
        }
        const bool event_parameter = binding->kind == ir::BindingKind::Event;
        std::string signature;
        std::string param_name;
        if (event_parameter) {
            bool typed = false;
            const std::optional<std::string> payload =
                payload_signature(binding->params, typed, param_name);
            if (!payload) {
                return fail(error,
                            "binding `" + binding->id + "` has an unsupported payload record");
            }
            signature = "void " + component.name + "::" + binding->region + "(" + *payload + ")";
        } else if (!binding->return_type.empty()) {
            const std::string type = handler_type(binding->return_type);
            signature = type + " " + component.name + "::" + binding->region + "()";
        } else {
            signature = "void " + component.name + "::" + binding->region + "()";
        }
        writer.open(signature);
        writer.line("// [DEVELOPER_LOGIC_START: " + binding->id + "]");
        writer.indent += 1;
        emit_stub_body(writer, *binding, event_parameter ? param_name : std::string());
        writer.indent -= 1;
        writer.line("// [DEVELOPER_LOGIC_END: " + binding->id + "]");
        if (has_update && event_parameter && binding->return_type.empty()) {
            writer.line("apply_state();");
        }
        writer.close("");
        writer.line("");
    }
    writer.close("");
    writer.close("");
    file.path = component.name + ".cpp";
    file.text = std::move(writer.text);
    return true;
}

