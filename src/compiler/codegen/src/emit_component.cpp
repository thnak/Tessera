// Component header/source emission for the C++ codegen slice (docs/design/compiler.md section 11).
//
// Generated shape (per component):
//   <Name>.hpp  struct <Name> { state/ref/animated/prop fields; dynamic child slots and card
//               tables; build(); handler_*(); apply_state(); apply_children_*/list helpers;
//               <region>(); };
//   <Name>.cpp  build() creating the static node tree plus detached conditional branches,
//               per-list item builders, the generated update path, handler bodies, and one
//               protected [DEVELOPER_LOGIC_START: bind::<id>] region per binding.
// Determinism: fields, children, handlers and bindings are emitted in IR order; maps are sorted;
// two-space indent; LF only. Nothing depends on clang-format or the wall clock.

