#pragma once

#include <string>
#include <string_view>

// Runtime entry point for the statically linked ICU data blob (docs/design/icu-data.md).
//
// The reduced package is compiled into the binary as a plain byte array; ICU only reaches it
// through `udata_setCommonData`, which must run before the first data-dependent call. The
// function is idempotent and is also invoked lazily by the segmentation and locale helpers, so a
// host does not have to sequence startup itself.
//
// This header stays free of ICU headers: the ICU slice is internal to the text module and the
// public UI headers never see a third-party type.
namespace tessera::ui::text::icu {

// False in builds that do not enable TESSERA_ICU_REDUCED_DATA; every function below then has a
// stub that reports "not linked" instead of failing at link time.
#if defined(TESSERA_ICU_ENABLED)
inline constexpr bool kLinked = true;
#else
inline constexpr bool kLinked = false;
#endif

// Compile-time description of the linked blob, generated by the reduced-data step. Empty in a
// build without the ICU slice.
struct BlobInfo {
    std::string_view data_name; // package ToC prefix, "icudt76l"
    std::string_view version;   // pinned ICU release, "76.1.0"
    std::string_view sha256;    // digest of the trimmed package
    long long bytes = 0;        // package size
    int items = 0;              // items in the package
    int locales = 0;            // kept locale bundles
};

enum class InitStatus {
    Ok,           // blob installed (this call or an earlier one)
    AlreadyReady, // no work needed
    NotLinked,    // build without the ICU slice
    Failed,       // ICU rejected the blob; see init_error()
};

// Installs the linked blob as ICU common data, then pins the ICU version. Idempotent and cheap
// after the first call.
[[nodiscard]] InitStatus initialize();

// True once initialize() succeeded.
[[nodiscard]] bool ready();

// The last initialization error, empty when none. Static storage: bounded and safe to log.
[[nodiscard]] std::string_view init_error();

// Library version ICU reports (`u_getVersion`), empty when not ready.
[[nodiscard]] std::string_view library_version();

// Name ICU reports for its common data after installation ("icudt76l"), empty when not ready.
[[nodiscard]] std::string_view package_name();

// Compile-time pins of the linked blob (empty/zero in a build without the ICU slice).
[[nodiscard]] BlobInfo blob_info();

#if !defined(TESSERA_ICU_ENABLED)
// Stub definitions for the ICU-free build, so a caller can be written once.
inline InitStatus initialize() {
    return InitStatus::NotLinked;
}
inline bool ready() {
    return false;
}
inline std::string_view init_error() {
    return {};
}
inline std::string_view library_version() {
    return {};
}
inline std::string_view package_name() {
    return {};
}
inline BlobInfo blob_info() {
    return {};
}
#endif

} // namespace tessera::ui::text::icu
